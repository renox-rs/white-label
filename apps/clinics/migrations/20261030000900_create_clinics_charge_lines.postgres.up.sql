ALTER TABLE "clinics_visits" ADD COLUMN work_accepted_by BIGINT;
ALTER TABLE "clinics_visits" ADD COLUMN work_accepted_at TIMESTAMPTZ;
ALTER TABLE "clinics_visits" ADD COLUMN not_suitable BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE "clinics_visits" ADD COLUMN deposit_refund_full BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE "clinics_visits" ADD COLUMN billed_at TIMESTAMPTZ;
ALTER TABLE "clinics_visits" ADD COLUMN invoice_id BIGINT;
ALTER TABLE "clinics_visits" ADD COLUMN payer_bill_id BIGINT;
ALTER TABLE "clinics_visits" ADD COLUMN authorisations_consumed_at TIMESTAMPTZ;
ALTER TABLE "clinics_visits" ADD COLUMN deposit_settled_at TIMESTAMPTZ;
ALTER TABLE "clinics_visits" ADD COLUMN patient_total BIGINT NOT NULL DEFAULT 0;
ALTER TABLE "clinics_visits" ADD COLUMN payer_total BIGINT NOT NULL DEFAULT 0;
ALTER TABLE "clinics_visits" ADD COLUMN deposit_applied BIGINT NOT NULL DEFAULT 0;
ALTER TABLE "clinics_visits" ADD COLUMN deposit_refunded BIGINT NOT NULL DEFAULT 0;
ALTER TABLE "clinics_visits" ADD COLUMN clinic_stop BOOLEAN NOT NULL DEFAULT FALSE;
