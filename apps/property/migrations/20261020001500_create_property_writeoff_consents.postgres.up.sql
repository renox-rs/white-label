-- The owner's consent to writing off the rent of a managed building (01
-- Property `FIN.ACL.15`, §4.1 row "A debt is uncollectable"; BL-PRP-18): a
-- note with the date and the owner contact who gave it, kept for the invoice.
CREATE TABLE "property_writeoff_consents" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    agreement_id BIGINT NOT NULL REFERENCES "property_management_agreements" (id),
    note TEXT NOT NULL,
    -- The owner's contact who gave it.
    given_by TEXT NOT NULL,
    given_on DATE NOT NULL,
    recorded_by BIGINT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX "property_writeoff_consents_invoice" ON "property_writeoff_consents" (invoice_id);
CREATE INDEX "property_writeoff_consents_agreement" ON "property_writeoff_consents" (agreement_id);
