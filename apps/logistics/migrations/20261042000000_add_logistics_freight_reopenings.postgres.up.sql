-- Reopening a closed freight job for a late cost (03 Logistics §4.2 row
-- *Supplier bill arrives after the job is closed*, §7.1 rows `close` and
-- `reopen`, §9 *VAT* and *Disbursements*; BL-LOG-22): each reopening with
-- its reason, whether a cost is a disbursement (the three conditions of
-- VATP013 recorded) and whether the evidence for zero-rating is attached.
CREATE TABLE "logistics_freight_reopenings" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES "logistics_freight_jobs" (id),
    -- `late_supplier_bill`, `demurrage`, `port_storage` or `other`.
    reason TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    -- The margin of the close it reopened, in fils.
    margin_before BIGINT NOT NULL,
    reopened_by BIGINT,
    reopened_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE INDEX "logistics_freight_reopenings_job" ON "logistics_freight_reopenings" (job_id);

-- The three conditions of VATP013 are recorded for this cost: it is a
-- disbursement, billed `out_of_scope` (`FIN.DSB.01`).
ALTER TABLE "logistics_job_lines" ADD COLUMN disbursement BOOLEAN NOT NULL DEFAULT FALSE;
-- The evidence for zero-rating is attached to the job (§9 *VAT*).
ALTER TABLE "logistics_freight_jobs" ADD COLUMN zero_rate_evidence BOOLEAN NOT NULL DEFAULT FALSE;
