-- A blocked client (03 Logistics §3.3 `PTY.ACL.03`, §4.1 row *Client
-- blocked*, §7.1 rows `pay` and `repay`; BL-LOG-19): the exception that lets
-- one remittance payment go ahead, and the freight jobs that new bookings of
-- a blocked client are refused for.

-- The company admin approved an exception for the remittance: the next `pay`
-- (or `repay`) goes ahead although the client is blocked, and uses it up.
ALTER TABLE "logistics_remittances" ADD COLUMN block_exception_granted BOOLEAN NOT NULL DEFAULT FALSE;

-- A freight job, as far as the block needs it: it is opened for a client
-- (refused while the client is blocked) and an open job continues. Its
-- lifecycle (departure, cancel, hold, reopen, close) is the freight issues'.
CREATE TABLE "logistics_freight_jobs" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number TEXT NOT NULL,
    client_party_id BIGINT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    opened_by BIGINT,
    notes TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'open',
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX "logistics_freight_jobs_number" ON "logistics_freight_jobs" (number);
CREATE INDEX "logistics_freight_jobs_client" ON "logistics_freight_jobs" (client_party_id);
