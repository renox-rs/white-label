-- 04 Accounting `ACC.RUL.09` (BL-ACC-04): the statutory deadline notice of a
-- suspension or an end, its delivery, reminder, escalation and the client
-- approver's acknowledgement in the portal.
CREATE TABLE "accounting_deadline_notices" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    engagement_id BIGINT NOT NULL REFERENCES "accounting_engagements" (id),
    client_party_id BIGINT NOT NULL,
    cause TEXT NOT NULL,
    prepared_for TEXT,
    on_date DATE NOT NULL,
    window_end DATE NOT NULL,
    lines TEXT NOT NULL,
    deadline_count BIGINT NOT NULL DEFAULT 0,
    task_id BIGINT,
    sent_at TIMESTAMPTZ,
    sent_by BIGINT,
    delivered_on DATE,
    reminded_on DATE,
    escalated_on DATE,
    escalation_task_id BIGINT,
    acknowledged_at TIMESTAMPTZ,
    acknowledged_by BIGINT,
    cancelled_on DATE,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE INDEX "accounting_deadline_notices_engagement_id" ON "accounting_deadline_notices" (engagement_id);
