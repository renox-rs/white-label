-- 08 Auto: vehicles that are not collected (`AUT.RUL.18`, BL-AUT-05). The daily
-- run remembers the days of its reminders (the first one starts the storage
-- fee), the day-30 task for the branch manager, and the storage fee invoice
-- raised at release; the client's switches (the storage fee is off until it is
-- turned on) are rows of `auto_settings`.
ALTER TABLE "auto_job_cards" ADD COLUMN collect_first_on DATE;
ALTER TABLE "auto_job_cards" ADD COLUMN collect_second_on DATE;
ALTER TABLE "auto_job_cards" ADD COLUMN collect_manager_on DATE;
ALTER TABLE "auto_job_cards" ADD COLUMN storage_days BIGINT NOT NULL DEFAULT 0;
ALTER TABLE "auto_job_cards" ADD COLUMN storage_invoice_id BIGINT;
ALTER TABLE "auto_job_cards" ADD COLUMN storage_invoiced_at TIMESTAMPTZ;

CREATE TABLE "auto_settings" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT NOT NULL,
    value TEXT NOT NULL,
    updated_by BIGINT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX "auto_settings_key" ON "auto_settings" (key);
