-- The work order (07 Manufacturing §6, §7.1): an instruction to produce a quantity of one item on one line. Quantities are thousandths of the base unit, money is fils.
CREATE TABLE "manufacturing_work_orders" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number TEXT NOT NULL,
    plant_id BIGINT NOT NULL REFERENCES "manufacturing_plants" (id),
    line_id BIGINT REFERENCES "manufacturing_lines" (id),
    item_id BIGINT NOT NULL,
    bom_id BIGINT,
    quantity_milli BIGINT NOT NULL,
    quantity_for_stock_milli BIGINT NOT NULL DEFAULT 0,
    planned_start DATE,
    planned_end DATE,
    source TEXT NOT NULL DEFAULT 'stock',
    sales_order_id BIGINT,
    sales_order_line_id BIGINT,
    status TEXT NOT NULL DEFAULT 'planned',
    hold_reason TEXT,
    std_material_cost BIGINT NOT NULL DEFAULT 0,
    std_unit_cost BIGINT NOT NULL DEFAULT 0,
    started_at TIMESTAMPTZ,
    stopped_at TIMESTAMPTZ,
    output_lot_id BIGINT,
    good_milli BIGINT NOT NULL DEFAULT 0,
    scrap_milli BIGINT NOT NULL DEFAULT 0,
    has_issue BOOLEAN NOT NULL DEFAULT FALSE,
    actual_cost BIGINT,
    cancel_reason TEXT,
    unlink_reason TEXT,
    unlinked_at TIMESTAMPTZ,
    abort_reason TEXT,
    abort_requested_by BIGINT,
    abort_approved_by BIGINT,
    abort_scrap_value BIGINT,
    abort_loss BIGINT,
    aborted_at TIMESTAMPTZ,
    abort_announced_at TIMESTAMPTZ,
    created_by BIGINT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX "manufacturing_work_orders_number" ON "manufacturing_work_orders" (number);
CREATE INDEX "manufacturing_work_orders_status" ON "manufacturing_work_orders" (status);
CREATE INDEX "manufacturing_work_orders_line" ON "manufacturing_work_orders" (line_id);
CREATE INDEX "manufacturing_work_orders_order" ON "manufacturing_work_orders" (sales_order_id, sales_order_line_id);
