-- The refunds after completion and the rider faults (06 F&B §4.2 row
-- *Complaint after delivery*, §10; BL-FNB-08). A refund fact is written when a
-- *no goods* return of an order is resolved (a complaint, a reversed delivery,
-- an aggregator's refund taken from a payout) so the report can group them by
-- category and responsible party, net and gross, by brand, outlet and channel.
-- A rider fault is the entry on the rider's record: order, category, amount,
-- date; it never touches pay.
CREATE TABLE "fnb_refund_facts" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_return_id BIGINT NOT NULL,
    sales_order_id BIGINT NOT NULL,
    order_id BIGINT,
    order_number TEXT NOT NULL DEFAULT '',
    brand_id BIGINT,
    outlet_id BIGINT,
    channel TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL,
    party TEXT NOT NULL,
    -- `refund`, `credit_note` or `refunded_by_channel`.
    resolution TEXT NOT NULL,
    -- With VAT, and the net of the VAT, in fils.
    gross BIGINT NOT NULL DEFAULT 0,
    net BIGINT NOT NULL DEFAULT 0,
    -- The business day (Asia/Dubai) the return was resolved.
    occurred_on DATE NOT NULL,
    -- When the return was taken back (a voided statement, a refund the
    -- aggregator reversed): the report leaves such a refund out.
    reversed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX "fnb_refund_facts_return" ON "fnb_refund_facts" (sales_return_id);
CREATE INDEX "fnb_refund_facts_day" ON "fnb_refund_facts" (occurred_on);

CREATE TABLE "fnb_rider_faults" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- `return:<id>` for a return naming the rider, `close:<order>` for a
    -- failed delivery closed with the rider responsible: one entry each.
    fault_key TEXT NOT NULL,
    order_id BIGINT NOT NULL,
    order_number TEXT NOT NULL DEFAULT '',
    sales_return_id BIGINT,
    -- The rider of the delivery's last run (a user) and their employee record.
    rider_user_id BIGINT,
    employee_id BIGINT,
    category TEXT NOT NULL,
    amount BIGINT NOT NULL DEFAULT 0,
    occurred_on DATE NOT NULL,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX "fnb_rider_faults_key" ON "fnb_rider_faults" (fault_key);
CREATE INDEX "fnb_rider_faults_employee" ON "fnb_rider_faults" (employee_id);
